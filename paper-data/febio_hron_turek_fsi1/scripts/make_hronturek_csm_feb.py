#!/usr/bin/env python3
"""Hron-Turek CSM1/CSM2 structural test (flag only) as an FEBio v4.13 static model.  Stage B of the FSI1 pilot.

Geometry (benchmark flag as in the solids4foam TurekHron2006 tutorial, system/solid/blockMeshDict): rectangle x in [x_root, 0.6], y in [0.19, 0.21];
default root x_root = 0.2 + sqrt(0.05^2 - 0.01^2) = 0.248989959... (the flag meets the cylinder circle there; clamp = whole root face), free length 0.351010.
--root 0.25 gives the nominal-length variant (L = 0.35), informational only.
Plane strain: one element thick slab (TZ), u_z = 0 on all nodes.  Material St.Venant-Kirchhoff (FEBio 'St.Venant-Kirchhoff'), rho = 1000, nu = 0.4,
E = 1.4e6 (CSM1) or 5.6e6 (CSM2).  Body force: FEBio const body load (acceleration; FEBio multiplies by the density and integrates over the REFERENCE volume),
y component of the PHYSICAL gravitational acceleration = --g (default -2). v2: FEBio const body_load is applied with the opposite sign to the acceleration (verified by run 14165: y = -2 gave an upward deflection), so the body_load y written is -g; node_data reactions need the plotfile var "reaction forces" (v2).  Static, load ramp over --steps steps, full Newton.
Mesh: nt elements across the thickness, nx = round(L/(h/nt)) along the length (aspect ratio about 1); hex8 or hex20 (hex20 uses the same nt x nx element grid).
Point A (0.6, 0.2): node at (0.6, 0.2, z=0); exists for even nt.  Output: pointA.txt (x,y,ux,uy), reactions of the root face, top line.
Usage: make_hronturek_csm_feb.py --nt 4 --elem hex8 --E 1.4e6 --out DIR --tag TAG [--g -2] [--root exact|0.25] [--steps 10]
"""
import argparse, os, json, hashlib, math

H, XR_EXACT, XTIP, YB, TZ = 0.02, 0.2 + math.sqrt(0.05**2 - 0.01**2), 0.6, 0.19, 0.015
NU, RHO = 0.4, 1000.0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--nt", type=int, required=True); ap.add_argument("--elem", choices=["hex8", "hex20"], default="hex8")
    ap.add_argument("--E", type=float, required=True); ap.add_argument("--g", type=float, default=-2.0)
    ap.add_argument("--root", default="exact"); ap.add_argument("--steps", type=int, default=10)
    ap.add_argument("--out", required=True); ap.add_argument("--tag", required=True)
    a = ap.parse_args()
    xr = XR_EXACT if a.root == "exact" else float(a.root)
    L = XTIP - xr
    nt = a.nt; nx = int(round(L / (H / nt)))
    q = 2 if a.elem == "hex20" else 1                       # grid refinement factor for node numbering
    X = lambda i: xr + L * i / (q * nx); Y = lambda j: YB + H * j / (q * nt); Z = lambda k: TZ * k / (2 if q == 2 else 1)
    nodes, used = [], {}
    def nid(i, j, k):
        if (i, j, k) not in used:
            nodes.append((X(i), Y(j), Z(k))); used[(i, j, k)] = len(nodes)
        return used[(i, j, k)]
    els = []
    for ex in range(nx):
        for ey in range(nt):
            i0, j0 = q * ex, q * ey
            if q == 1:
                c = lambda da, db, k: nid(i0 + da, j0 + db, k)
                els.append([c(0, 0, 0), c(1, 0, 0), c(1, 1, 0), c(0, 1, 0), c(0, 0, 1), c(1, 0, 1), c(1, 1, 1), c(0, 1, 1)])
            else:
                c = lambda da, db, k: nid(i0 + da, j0 + db, k)
                corners = [c(0, 0, 0), c(2, 0, 0), c(2, 2, 0), c(0, 2, 0), c(0, 0, 2), c(2, 0, 2), c(2, 2, 2), c(0, 2, 2)]
                mb = [c(1, 0, 0), c(2, 1, 0), c(1, 2, 0), c(0, 1, 0)]; mt = [c(1, 0, 2), c(2, 1, 2), c(1, 2, 2), c(0, 1, 2)]
                vert = [c(0, 0, 1), c(2, 0, 1), c(2, 2, 1), c(0, 2, 1)]
                els.append(corners + mb + mt + vert)
    eps = 1e-9
    root = [n for n, (x, y, z) in enumerate(nodes, 1) if abs(x - xr) < eps]
    A = [n for n, (x, y, z) in enumerate(nodes, 1) if abs(x - XTIP) < eps and abs(y - 0.2) < eps and abs(z) < eps]
    assert len(A) == 1, ("point A node", A)
    top = [n for n, (x, y, z) in enumerate(nodes, 1) if abs(y - (YB + H)) < eps and abs(z) < eps]
    lst = lambda l: ",".join(map(str, l))
    o = []; w = o.append
    w('<?xml version="1.0" encoding="ISO-8859-1"?>')
    w(f'<!-- Hron-Turek CSM structural flag, {a.tag}. Generated by tools/make_hronturek_csm_feb.py -->')
    w('<febio_spec version="4.0">\n\t<Module type="solid"/>')
    w('\t<Control><analysis>STATIC</analysis>')
    w(f'\t\t<time_steps>{a.steps}</time_steps><step_size>{1.0/a.steps:.12g}</step_size>')
    w('\t\t<plot_zero_state>0</plot_zero_state><plot_range>0,-1</plot_range><plot_level>PLOT_MAJOR_ITRS</plot_level>')
    w('\t\t<output_level>OUTPUT_MAJOR_ITRS</output_level>')
    w('\t\t<solver type="solid"><symmetric_stiffness>symmetric</symmetric_stiffness><max_refs>25</max_refs>')
    w('\t\t\t<dtol>1e-8</dtol><etol>1e-12</etol><rtol>0</rtol><lstol>0.9</lstol><min_residual>1e-30</min_residual>')
    w('\t\t\t<qn_method type="full Newton"/></solver>')
    w('\t</Control>')
    w(f'\t<Material><material id="1" name="Flag" type="St.Venant-Kirchhoff"><density>{RHO:g}</density><E>{a.E:.12g}</E><v>{NU:g}</v></material></Material>')
    w('\t<Mesh>\n\t\t<Nodes name="AllNodes">')
    for n, (x, y, z) in enumerate(nodes, 1):
        w(f'\t\t\t<node id="{n}">{x:.15g},{y:.15g},{z:.15g}</node>')
    w(f'\t\t</Nodes>\n\t\t<Elements type="{a.elem}" name="Flag">')
    for i, e in enumerate(els, 1):
        w(f'\t\t\t<elem id="{i}">{lst(e)}</elem>')
    w('\t\t</Elements>')
    w(f'\t\t<NodeSet name="All">{lst(range(1, len(nodes) + 1))}</NodeSet>')
    w(f'\t\t<NodeSet name="Root">{lst(root)}</NodeSet><NodeSet name="PointA">{lst(A)}</NodeSet><NodeSet name="TopLine">{lst(top)}</NodeSet>')
    w('\t</Mesh>\n\t<MeshDomains><SolidDomain name="Flag" mat="Flag"/></MeshDomains>')
    w('\t<Boundary>')
    w('\t\t<bc name="uz" node_set="All" type="zero displacement"><x_dof>0</x_dof><y_dof>0</y_dof><z_dof>1</z_dof></bc>')
    w('\t\t<bc name="clamp" node_set="Root" type="zero displacement"><x_dof>1</x_dof><y_dof>1</y_dof><z_dof>0</z_dof></bc>')
    w('\t</Boundary>')
    w(f'\t<Loads><body_load type="const"><x lc="1">0</x><y lc="1">{-a.g:.12g}</y><z lc="1">0</z></body_load></Loads>')
    w('\t<LoadData><load_controller id="1" name="ramp" type="loadcurve"><interpolate>LINEAR</interpolate>'
      '<points><pt>0,0</pt><pt>1,1</pt></points></load_controller></LoadData>')
    w('\t<Output>\n\t\t<plotfile type="febio"><var type="displacement"/><var type="stress"/><var type="reaction forces"/></plotfile>\n\t\t<logfile>')
    w(f'\t\t\t<node_data data="x;y;ux;uy;uz" file="pointA.txt" delim=" ">{lst(A)}</node_data>')
    w(f'\t\t\t<node_data data="x;y;ux;uy" file="topline.txt" delim=" ">{lst(top)}</node_data>')
    w(f'\t\t\t<node_data data="Rx;Ry;Rz" file="react_root.txt" delim=" ">{lst(root)}</node_data>')
    w('\t\t</logfile>\n\t</Output>\n</febio_spec>')
    text = "\n".join(o) + "\n"
    os.makedirs(a.out, exist_ok=True)
    open(os.path.join(a.out, f"{a.tag}.feb"), "w", encoding="latin-1").write(text)
    # quality: element aspect, positive Jacobian (axis-aligned grid: dx/dy)
    dx, dy = L / nx, H / nt
    meta = dict(vars(a), x_root=xr, length=L, nx=nx, nt=nt, n_nodes=len(nodes), n_elem=len(els), dx=dx, dy=dy, aspect=dx / dy, thickness_z=TZ,
                point_A_node=A[0], root_nodes=len(root), rho=RHO, nu=NU,
                weight_total=RHO * abs(a.g) * L * H * TZ,
                feb_sha256=hashlib.sha256(text.encode("latin-1")).hexdigest(), generator="tools/make_hronturek_csm_feb.py v2", febio_body_load_y=-a.g)
    json.dump(meta, open(os.path.join(a.out, "model_meta.json"), "w"), indent=1)
    print(a.tag, a.elem, f"nt={nt} nx={nx} L={L:.6f} nodes={len(nodes)} elems={len(els)} aspect={dx/dy:.3f} A={A[0]}")


if __name__ == "__main__":
    main()
