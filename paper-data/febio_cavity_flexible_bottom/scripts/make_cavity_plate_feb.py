#!/usr/bin/env python3
import os, os as _os; HERE = _os.path.dirname(_os.path.abspath(__file__)); PKG = _os.path.dirname(HERE)   # package root; run directories of retained HPC outputs: env CAVITY_RUNS (default runs/cavityNext)
"""cavityFlexibleBottom B0: plate-only FEBio model (plane strain, StVK, uniform follower pressure).

Plate x in [2,6], y in [-0.4,0], one element thick in z (u_z = 0 on all nodes -> plane strain),
clamped at x = 2 and x = 6, E = 500 Pa, nu = 0.4, St.Venant-Kirchhoff, follower pressure p on y = 0 (pushing down).
Quadratic hex20 elements, nx x ny elements in the plane (reference: 20x2 and 40x4 Q9 -> u_y(A) -0.23887 / -0.24047 m).
Usage: make_cavity_plate_feb.py --nx 20 --ny 2 --out DIR --tag TAG [--steps 10] [--p 1.315] [--law stvk|neo|linear-free]
"""
import argparse, os, json, hashlib

L0, L1, YB, YT, TZ = 2.0, 6.0, -0.4, 0.0, 0.1   # thickness in z is arbitrary for plane strain (force reported per TZ)
E, NU, RHO = 500.0, 0.4, 1000.0


def build(nx, ny):
    gx, gy = 2 * nx + 1, 2 * ny + 1
    X = lambda i: L0 + (L1 - L0) * i / (2 * nx)
    Y = lambda j: YB + (YT - YB) * j / (2 * ny)
    Z = lambda k: TZ * k / 2
    used, nodes = {}, []

    def nid(i, j, k):
        key = (i, j, k)
        if key not in used:
            nodes.append((X(i), Y(j), Z(k)))
            used[key] = len(nodes)
        return used[key]
    els, top = [], []
    for ex in range(nx):
        for ey in range(ny):
            i0, j0 = 2 * ex, 2 * ey
            c = lambda a, b, k: nid(i0 + a, j0 + b, k)
            corners = [c(0, 0, 0), c(2, 0, 0), c(2, 2, 0), c(0, 2, 0), c(0, 0, 2), c(2, 0, 2), c(2, 2, 2), c(0, 2, 2)]
            mid_b = [c(1, 0, 0), c(2, 1, 0), c(1, 2, 0), c(0, 1, 0)]
            mid_t = [c(1, 0, 2), c(2, 1, 2), c(1, 2, 2), c(0, 1, 2)]
            vert = [c(0, 0, 1), c(2, 0, 1), c(2, 2, 1), c(0, 2, 1)]
            els.append(corners + mid_b + mid_t + vert)
            if ey == ny - 1:   # top face (y = 0), normal +y: order x0z0 -> x0z1 -> x1z1 -> x1z0
                top.append([c(0, 2, 0), c(0, 2, 2), c(2, 2, 2), c(2, 2, 0), c(0, 2, 1), c(1, 2, 2), c(2, 2, 1), c(1, 2, 0)])
    return nodes, els, top


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--nx", type=int, required=True); ap.add_argument("--ny", type=int, required=True)
    ap.add_argument("--p", type=float, default=1.315); ap.add_argument("--steps", type=int, default=10)
    ap.add_argument("--law", default="stvk", choices=["stvk", "neo"])
    ap.add_argument("--out", required=True); ap.add_argument("--tag", required=True)
    a = ap.parse_args()
    nodes, els, top = build(a.nx, a.ny)
    eps = 1e-9
    left = [n for n, (x, y, z) in enumerate(nodes, 1) if abs(x - L0) < eps]
    right = [n for n, (x, y, z) in enumerate(nodes, 1) if abs(x - L1) < eps]
    A = [n for n, (x, y, z) in enumerate(nodes, 1) if abs(x - 4.0) < eps and abs(y - YT) < eps and abs(z) < eps]
    assert len(A) == 1, A
    topn = [n for n, (x, y, z) in enumerate(nodes, 1) if abs(y - YT) < eps and abs(z) < eps]
    lst = lambda l: ",".join(map(str, l))
    o = []; w = o.append
    w('<?xml version="1.0" encoding="ISO-8859-1"?>')
    w(f'<!-- cavityFlexibleBottom B0 plate-only: {a.tag}. Generated by tools/make_cavity_plate_feb.py -->')
    w('<febio_spec version="4.0">')
    w('\t<Module type="solid"/>')
    w('\t<Control><analysis>STATIC</analysis>')
    w(f'\t\t<time_steps>{a.steps}</time_steps><step_size>{1.0/a.steps:.12g}</step_size>')
    w('\t\t<plot_zero_state>0</plot_zero_state><plot_range>0,-1</plot_range><plot_level>PLOT_MAJOR_ITRS</plot_level>')
    w('\t\t<output_level>OUTPUT_MAJOR_ITRS</output_level>')
    w('\t\t<solver type="solid"><symmetric_stiffness>symmetric</symmetric_stiffness><max_refs>15</max_refs>')
    w('\t\t\t<dtol>0.001</dtol><etol>0.01</etol><rtol>0</rtol><lstol>0.9</lstol><min_residual>1e-20</min_residual>')
    w('\t\t\t<qn_method type="BFGS"><max_ups>0</max_ups></qn_method></solver>')
    w('\t</Control>')
    w('\t<Material>')
    if a.law == "stvk":
        w(f'\t\t<material id="1" name="Plate" type="St.Venant-Kirchhoff"><density>{RHO:g}</density><E>{E:g}</E><v>{NU:g}</v></material>')
    else:
        w(f'\t\t<material id="1" name="Plate" type="neo-Hookean"><density>{RHO:g}</density><E>{E:g}</E><v>{NU:g}</v></material>')
    w('\t</Material>')
    w('\t<Mesh>')
    w('\t\t<Nodes name="AllNodes">')
    for n, (x, y, z) in enumerate(nodes, 1):
        w(f'\t\t\t<node id="{n}">{x:.15g},{y:.15g},{z:.15g}</node>')
    w('\t\t</Nodes>')
    w('\t\t<Elements type="hex20" name="Plate">')
    for i, e in enumerate(els, 1):
        w(f'\t\t\t<elem id="{i}">{lst(e)}</elem>')
    w('\t\t</Elements>')
    w(f'\t\t<NodeSet name="All">{lst(range(1, len(nodes) + 1))}</NodeSet>')
    w(f'\t\t<NodeSet name="Left">{lst(left)}</NodeSet><NodeSet name="Right">{lst(right)}</NodeSet>')
    w(f'\t\t<NodeSet name="PointA">{lst(A)}</NodeSet><NodeSet name="TopLine">{lst(topn)}</NodeSet>')
    w('\t\t<Surface name="Top">')
    for i, q in enumerate(top, 1):
        w(f'\t\t\t<quad8 id="{i}">{lst(q)}</quad8>')
    w('\t\t</Surface>')
    w('\t</Mesh>')
    w('\t<MeshDomains><SolidDomain name="Plate" mat="Plate"/></MeshDomains>')
    w('\t<Boundary>')
    w('\t\t<bc name="uz" node_set="All" type="zero displacement"><x_dof>0</x_dof><y_dof>0</y_dof><z_dof>1</z_dof></bc>')
    w('\t\t<bc name="clampL" node_set="Left" type="zero displacement"><x_dof>1</x_dof><y_dof>1</y_dof><z_dof>0</z_dof></bc>')
    w('\t\t<bc name="clampR" node_set="Right" type="zero displacement"><x_dof>1</x_dof><y_dof>1</y_dof><z_dof>0</z_dof></bc>')
    w('\t</Boundary>')
    w('\t<Loads>')
    w(f'\t\t<surface_load name="FluidPressure" surface="Top" type="pressure"><pressure lc="1">{a.p:.12g}</pressure>'
      '<symmetric_stiffness>1</symmetric_stiffness><linear>0</linear><shell_bottom>0</shell_bottom></surface_load>')
    w('\t</Loads>')
    w('\t<LoadData><load_controller id="1" name="ramp" type="loadcurve"><interpolate>LINEAR</interpolate>'
      '<points><pt>0,0</pt><pt>1,1</pt></points></load_controller></LoadData>')
    w('\t<Output>')
    w('\t\t<plotfile type="febio"><var type="displacement"/><var type="stress"/><var type="reaction forces"/></plotfile>')
    w('\t\t<logfile>')
    w(f'\t\t\t<node_data data="x;y;ux;uy" file="pointA.txt" delim=" ">{lst(A)}</node_data>')
    w(f'\t\t\t<node_data data="x;y;ux;uy" file="topline.txt" delim=" ">{lst(topn)}</node_data>')
    w(f'\t\t\t<node_data data="Rx;Ry;Rz" file="react_left.txt" delim=" ">{lst(left)}</node_data>')
    w(f'\t\t\t<node_data data="Rx;Ry;Rz" file="react_right.txt" delim=" ">{lst(right)}</node_data>')
    w('\t\t\t<element_data data="J" file="J.txt" delim=" "/>')
    w('\t\t</logfile>')
    w('\t</Output>')
    w('</febio_spec>')
    text = "\n".join(o) + "\n"
    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(a.out, f"{a.tag}.feb"), "w", encoding="latin-1") as fh:
        fh.write(text)
    meta = dict(vars(a), n_nodes=len(nodes), n_elem=len(els), point_A_node=A[0], thickness_z=TZ,
                feb_sha256=hashlib.sha256(text.encode("latin-1")).hexdigest(),
                note="u_y(A) references (Q9 plane strain StVK): 20x2 -0.23887, 40x4 -0.24047 m (manuscript plate_laws.py)")
    json.dump(meta, open(os.path.join(a.out, "model_meta.json"), "w"), indent=1)
    print(a.tag, meta["n_nodes"], "nodes", meta["n_elem"], "hex20 elements, A node", A[0])


if __name__ == "__main__":
    main()
